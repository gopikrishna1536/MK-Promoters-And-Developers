-- Run this SQL in Supabase SQL Editor.
-- Admin users should be created manually in Supabase Authentication; public sign-up is not part of this starter.
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null default 'Open Plots' check (type in ('Open Plots','Residential','Commercial','Land')),
  status text not null default 'Ongoing' check (status in ('Upcoming','Ongoing','Completed')),
  location text,
  description text,
  image_url text,
  published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  email text,
  interest text not null default 'General enquiry',
  message text,
  created_at timestamptz not null default now()
);

alter table public.projects enable row level security;
alter table public.enquiries enable row level security;

-- Visitors can only read published projects.
drop policy if exists "Anyone can view published projects" on public.projects;
create policy "Anyone can view published projects" on public.projects
  for select to anon, authenticated using (published = true);

-- Signed-in admins can manage projects. Only create admin accounts you control.
drop policy if exists "Authenticated admins can manage projects" on public.projects;
create policy "Authenticated admins can manage projects" on public.projects
  for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

-- Visitors can submit enquiries. Do not allow anonymous users to read them.
drop policy if exists "Visitors can submit enquiries" on public.enquiries;
create policy "Visitors can submit enquiries" on public.enquiries
  for insert to anon, authenticated with check (true);
drop policy if exists "Authenticated admins can read enquiries" on public.enquiries;
create policy "Authenticated admins can read enquiries" on public.enquiries
  for select to authenticated using (auth.uid() is not null);
drop policy if exists "Authenticated admins can delete enquiries" on public.enquiries;
create policy "Authenticated admins can delete enquiries" on public.enquiries
  for delete to authenticated using (auth.uid() is not null);

grant select on public.projects to anon, authenticated;
grant insert, update, delete on public.projects to authenticated;
grant insert on public.enquiries to anon, authenticated;
grant select, delete on public.enquiries to authenticated;
grant usage, select on all sequences in schema public to authenticated;
